package com.collection.hashset.example;

import java.util.HashSet;

public class SetExample {

	public static void main(String[] args) {
		
		HashSet<String> city = new HashSet<String>();
		
		city.add("BLR");
		city.add("HYD");
		city.add("DEL");
		city.add("LKO");
		city.add("KNP");
		
		System.out.println(city);
		
		
	}

}
